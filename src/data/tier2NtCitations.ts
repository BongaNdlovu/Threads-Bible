// Bidirectional indexes for instant lookup with multi-verse range expansion
export const NT_LOOKUP = new Map<string, NtCitation[]>();
export const OT_LOOKUP = new Map<string, NtCitation[]>();

for (const cit of NT_CITATIONS) {
  // Index all NT verses in the quotation/allusion range
  const ntVerses = new Set<string>([cit.ntVerseId, ...expandVerseRange(cit.ntRef)]);
  for (const vId of ntVerses) {
    if (!NT_LOOKUP.has(vId)) NT_LOOKUP.set(vId, []);
    const list = NT_LOOKUP.get(vId)!;
    if (!list.some(c => c.id === cit.id)) list.push(cit);
  }

  // Index all OT verses in the quoted passage range
  const otVerses = new Set<string>([cit.otVerseId, ...expandVerseRange(cit.otRef)]);
  for (const vId of otVerses) {
    if (!OT_LOOKUP.has(vId)) OT_LOOKUP.set(vId, []);
    const list = OT_LOOKUP.get(vId)!;
    if (!list.some(c => c.id === cit.id)) list.push(cit);
  }
}

export function getCitationsForNtVerse(verseId: string): NtCitation[] {
  return NT_LOOKUP.get(verseId) || [];
}

export function getCitationsForOtVerse(verseId: string): NtCitation[] {
  return OT_LOOKUP.get(verseId) || [];
}

export function getCitationsForVerse(verseId: string): NtCitation[] {
  const nt = getCitationsForNtVerse(verseId);
  const ot = getCitationsForOtVerse(verseId);
  const combined = [...nt, ...ot];
  if (combined.length <= 1) return combined;
  const seen = new Set<string>();
  return combined.filter(c => {
    if (seen.has(c.id)) return false;
    seen.add(c.id);
    return true;
  });
}

